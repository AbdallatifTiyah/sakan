## ٧. حقوقك

- **تشوف** شو محفوظ عنك
- **تصحّح** أي معلومة غلط
- **تحذف** ملفك وإعلاناتك وطلباتك
- **تسحب موافقتك** وتوقف التواصل

اطلب أي واحد منهم عبر نموذج التواصل. بنرد خلال ١٤ يوم.

**استثناء واحد**: البلاغات المرتبطة بسلامة أشخاص تانيين ما بنقدر نحذفها، بس بنقدر نخفي هويتك منها.

