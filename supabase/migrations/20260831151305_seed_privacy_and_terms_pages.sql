## ٥. مين بيشوف بياناتك

- **أنت.**
- **فريق سكن**: العاملون في المنصة والمندوبون الميدانيون، بحدود شغلهم فقط. كل إجراء بينتسجّل باسم صاحبه.
- **الطرف التاني بالصفقة**: لما ترسل طلب تواصل، بنعطي المالك اسمك ورقمك. هاد هو الغرض من الطلب.
- **الجهات الرسمية**: إذا طُلب منا قانونياً، أو إذا كان في خطر مباشر على سلامة شخص.

سيرفراتنا عند Supabase في فرانكفورت — ألمانيا، والموقع بينخدم عبر Cloudflare. هدول مزودون تقنيون بيعالجوا البيانات لصالحنا وما بيستخدموها لأغراضهم.

