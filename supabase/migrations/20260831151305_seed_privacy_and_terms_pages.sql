## ٢. شو بنجمع

### إذا سجّلت غرفة للإيجار

- اسمك الأول ورقم واتسابك
- تفاصيل الغرفة: العنوان، الوصف، السعر، التأمين، المنطقة، النوع، المواصفات، تاريخ التوفّر
- العلامة المميزة القريبة، والعنوان الدقيق إذا أعطيتنا إياه للزيارة الميدانية
- ملاحظات مندوبنا بعد الزيارة، إن صارت

### إذا سجّلت طلب سكن

- اسمك الأول ورقم واتسابك
- الجنس، الصفة (طالب/موظف/غير ذلك)، الميزانية، المدينة والمناطق المفضّلة، تاريخ الانتقال، صفاتك كساكن، وأي ملاحظات كتبتها

### إذا أرسلت طلب تواصل أو بلاغ

- اسمك ورقمك (الرقم اختياري بالبلاغ)
- نص البلاغ وتصنيفه

### تلقائياً

الموقع **ما بيستخدم كوكيز ولا أدوات تتبّع ولا تحليلات**. بنستخدم خط عربي مستضاف عند Google Fonts، وهاد بيعني إنه Google بيشوف عنوان الـIP تبعك وقت تحميل الصفحة — هاد الشي الوحيد اللي بيروح لطرف تالت، وما بنقدر نتحكم فيه غير بشيل الخط.

