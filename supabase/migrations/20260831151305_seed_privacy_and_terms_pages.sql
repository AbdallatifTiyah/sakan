## ٩. السلامة — حدود دورنا

سكن **مش طرف بعقد الإيجار**. إحنا بنوثّق ونوصل، والاتفاق بينك وبين الطرف التاني.

التوثيق عنا مستويين:
- **موثّق هاتفياً**: تكلمنا مع المالك وتأكدنا إنه موجود وإنه الإعلان حقيقي
- **موثّق ميدانياً**: مندوبنا زار المكان وفحص بنود محددة

**ملاحظات الزيارة بتوصف حالة المكان يوم الزيارة، مش ضمانة دائمة.** إذا لاحظت إشي مخالف، بلّغنا فوراً.

المنصة **مش أداة مراقبة**. ما بنوفّر لأي حدا — لا للأهل ولا للمالك — طريقة يتابع فيها ساكن.

