## ٦. قدّيش بنحتفظ

- **الإعلانات**: بتنتهي تلقائياً بعد ٢١ يوم إلا إذا أكّد المالك إنها لسا متاحة
- **طلبات السكن**: بتنتهي بنفس المدة بعد النشر
- **ملف المالك أو الباحث**: بيضل محفوظ عشان نعرف تاريخ التعامل ونمنع تكرار المشاكل
- **البلاغات وسجلات الإجراءات**: بتضل محفوظة — هاي سجلات سلامة

بتقدر تطلب حذف ملفك بأي وقت.

