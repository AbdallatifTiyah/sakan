## باختصار

سكن منصة بتوصل بين ملّاك الغرف والباحثين عن سكن في رام الله والبيرة وبيرزيت.

عشان تشتغل المنصة لازم نجمع منك شوية معلومات. هاي الصفحة بتحكيلك بالضبط شو بنجمع، ليش، ومين بيشوفه.

**ثلاث قواعد ما بنكسرها:**

1. **رقم هاتفك ما بينعرض على الموقع أبداً** — لا للباحثين ولا للملّاك ولا لمحركات البحث.
2. **العنوان الدقيق ما بينعرض** — بنعرض المنطقة والعلامة المميزة بس.
3. **ما بنبيع بياناتك ولا بنأجّرها لأي جهة.**

