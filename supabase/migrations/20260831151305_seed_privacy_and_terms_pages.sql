## ١. مين إحنا

سكن — منصة تأجير غرف وسكن مشترك موثّق، بتشتغل في رام الله والبيرة وبيرزيت.

للتواصل بأي سؤال عن خصوصيتك أو لطلب حذف بياناتك، استخدم نموذج «تواصل معنا أو قدّم شكوى» أسفل أي صفحة، واختر «استفسار عام».

