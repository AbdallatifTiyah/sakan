## ٨. الأمان

- الاتصال بالموقع كله مشفّر (HTTPS)
- أرقام الهواتف والعناوين الدقيقة محجوبة على مستوى قاعدة البيانات نفسها، مش بالواجهة — يعني حتى لو صار خطأ برمجي بالموقع، ما بتظهر
- مركز التحكم محمي وما بيوصله إلا فريق سكن
- كل إجراء إداري بينتسجّل باسم صاحبه ووقته

