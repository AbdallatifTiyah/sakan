## باختصار

سكن منصة بتوصل بين ملّاك الغرف والباحثين عن سكن في رام الله والبيرة وبيرزيت. كل إعلان بينتوثّق قبل النشر، وأرقام الهواتف محمية دايماً.

---

## إذا بتدوّر على سكن

1. **تصفّح الإعلانات** بدون تسجيل ولا حساب — فلترة بالمدينة والمنطقة والسعر والنوع، وبحث نصي بالعنوان والوصف.
2. **افتح أي إعلان** لتشوف التفاصيل الكاملة: السعر، المواصفات، نتيجة الزيارة الميدانية إن صارت، وصور الغرفة.
3. **اترك اسمك ورقمك** بزر «أرسل طلب تواصل» — ما بنعرض رقمك للمالك إلا بعد ما توافق بإرسال الطلب.
4. **بنتواصل معك خلال ٢٤ ساعة** لنوصلك بالمالك.

**مجاناً بالكامل** خلال فترة الإطلاق. ما في رسوم على الباحث عن سكن.

ما لقيت غرفة تناسبك؟ سجّل طلبك من تبويب «باحثون عن سكن» وبنخبرك أول ما تنزل غرفة مطابقة.

---

## إذا عندك غرفة للإيجار

1. **سجّل الإعلان** من زر «أضف غرفة» — التفاصيل، الصور (لحد ٦)، والسعر.
2. **بنتواصل معك خلال ٢٤ ساعة** للتوثيق الهاتفي قبل النشر.
3. **الإعلان بينشر** بعد التوثيق، وبيضل فعّال ٢١ يوم — بعدها لازم تأكّد إنه لسا متاح عبر رابط بنبعتلك إياه، وإلا بينتهي تلقائياً.
4. **لما يتأجّر عبر المنصة**، بتدفع رسم نجاح مرة وحدة، بينحصّل نقداً عبر مندوبنا. القيمة معروضة وقت التسجيل، وما بتتغيّر بعد الاتفاق.

التفاصيل الكاملة بصفحة **شروط الاستخدام**.

