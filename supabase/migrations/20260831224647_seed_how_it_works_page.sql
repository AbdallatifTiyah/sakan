## مستويات التوثيق

| المستوى | يعني إيش |
|---|---|
| **موثّق هاتفياً** | تكلمنا مع المالك وتأكدنا إنه موجود وإنه الإعلان حقيقي |
| **موثّق ميدانياً** | مندوبنا زار المكان شخصياً وفحص بنود محددة (قفل الباب، مطابقة الصور، عدد الساكنين، وغيرها) |

ملاحظات الزيارة الميدانية بتوصف حالة المكان يوم الزيارة، مش ضمانة دائمة. إذا لاحظت إشي مخالف بعد الزيارة، بلّغنا فوراً.

