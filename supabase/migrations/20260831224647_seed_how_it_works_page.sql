## السلامة والبلاغات

سكن **مش طرف بعقد الإيجار** — إحنا بنوثّق ونوصل، والاتفاق بينك وبين الطرف التاني. لو صار إشي مخالف — قبل التأجير أو بعده — قدّم بلاغ من زر «تواصل معنا أو قدّم شكوى» أسفل أي صفحة. البلاغات الخطيرة (زي التحرش أو دخول الغرفة بدون إذن) بتوقف الإعلان تلقائياً لحد المراجعة.

المنصة **مش أداة مراقبة**. ما بنوفّر لأي حدا — لا للأهل ولا للمالك — طريقة يتابع فيها ساكن.

